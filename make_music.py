#!/usr/bin/env python3
"""make_music.py - build music_rom.v (3 square-wave voices) for music.v

  python3 tools/make_music.py --demo                 
  original built-in loop (what ships in the repo)

  python3 tools/make_music.py song.mp3 --seconds 30 
  convert your own audio file (needs ffmpeg + numpy)

output: music_rom.v with modules music_rom0/1/2. each entry is 24 bits: {len[7:0], div[15:0]}
div = half-period in clocks (0 = rest), len = duration in ticks, len 0 = end of track (loop)
timing has to match music.v: TICK_FRAMES frames per tick at 60 fps, CLK_HZ = 128*64*60
the converted rom is whatever you feed it
"""
import argparse, subprocess, sys
import numpy as np

CLK_HZ = 128 * 64 * 60
TICK_FRAMES = 4
TICK_S = TICK_FRAMES / 60.0

def midi_div(m):
    f = 440.0 * 2 ** ((m - 69) / 12.0)
    return max(1, int(round(CLK_HZ / (2 * f))))

def rle(notes, nticks):
    """notes: list of midi (or 0 = rest) per tick -> [(div, len)] with len<=255, padded to nticks"""
    notes = list(notes) + [0] * (nticks - len(notes))
    out, i = [], 0
    while i < nticks:
        j = i
        while j < nticks and notes[j] == notes[i] and j - i < 255:
            j += 1
        out.append((midi_div(notes[i]) if notes[i] else 0, j - i))
        i = j
    return out

def demo():
    # original 16-bar loop in A minor: lead, arpeggio, bass. 1 tick = 1/15 s, 2 ticks per 8th note => 450 bpm-ish 8ths (fast & arcade-y)
    A, C, D, E, F, G = 57, 60, 62, 64, 65, 67
    prog = [(45, [57, 60, 64]), (41, [53, 57, 60]), (48, [55, 60, 64]), (43, [55, 59, 62])]   # bass note + chord tones
    lead_pat = [
        [76, 0, 72, 0, 76, 0, 79, 0], [77, 0, 74, 0, 77, 0, 81, 0],
        [79, 0, 76, 0, 72, 0, 76, 0], [74, 0, 71, 0, 74, 0, 67, 0]]
    lead, arp, bass = [], [], []
    for rep in range(2):
        for bar, (b, ch) in enumerate(prog):
            for step in range(8):
                n = lead_pat[bar][step]
                if rep == 1 and step == 7:
                    n = lead_pat[bar][6] + 12 if bar % 2 == 0 else 0     # little variation on the repeat
                lead += [n, n] if n else [0, 0]
                arp += [ch[step % 3]] * 2
                bass += [b] * 2 if step % 2 == 0 else [0, 0]
    return lead, arp, bass

def from_audio(path, seconds):
    raw = subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-t", str(seconds), "-ac", "1", "-ar", "16000", "-f", "f32le", "-"],
                         capture_output=True, check=True).stdout
    x = np.frombuffer(raw, np.float32)
    sr, hop, win = 16000, int(16000 * TICK_S), 2048
    nt = len(x) // hop
    w = np.hanning(win)
    freqs = np.fft.rfftfreq(win, 1 / sr)
    def band(lo, hi): return (freqs >= lo) & (freqs < hi)
    bands = [band(250, 2000), band(250, 2000), band(50, 250)]        # lead, 2nd peak of lead band, bass
    voices = [[0] * nt for _ in range(3)]
    for t in range(nt):
        seg = x[max(0, t * hop - win // 4): max(0, t * hop - win // 4) + win]
        if len(seg) < win or np.abs(seg).max() < 0.01:
            continue
        mag = np.abs(np.fft.rfft(seg * w))
        for v in (0, 1, 2):
            m = np.where(bands[v], mag, 0)
            if v == 1:                                    # kill the lead peak +-1.5 semitones, take the next
                k0 = np.argmax(np.where(bands[0], mag, 0))
                m[(freqs > freqs[k0] * 0.917) & (freqs < freqs[k0] * 1.09)] = 0
                m[(freqs > freqs[k0] * 1.9) & (freqs < freqs[k0] * 2.1)] = 0      # and its octave harmonic
            k = int(np.argmax(m))
            if m[k] > 0.12 * mag.max() and freqs[k] > 0:
                voices[v][t] = int(round(69 + 12 * np.log2(freqs[k] / 440.0)))
    for v in voices:                                       # 3-tap median to kill one-tick glitches
        a = np.array(v)
        for t in range(1, len(a) - 1):
            tri = sorted([a[t - 1], a[t], a[t + 1]])
            a[t] = tri[1] if tri[1] != 0 or a[t] == 0 else a[t]
        v[:] = a.tolist()
    return voices

def emit(voices, path, name):
    nt = max(len(v) for v in voices)
    tracks = [rle(v, nt) for v in voices]
    abits = 10                                   # music.v AW; 1023 entries per voice max
    if max(len(t) for t in tracks) > 1023: sys.exit('too many notes: use --seconds smaller')
    with open(path, "w") as f:
        f.write(f"// music_rom.v - generated by tools/make_music.py ({name}); do not edit by hand\n")
        f.write(f"// tick = {TICK_FRAMES} frames, loop = {nt} ticks ({nt * TICK_S:.1f} s)\n")
        for i, t in enumerate(tracks):
            f.write(f"module music_rom{i}(input wire [{abits-1}:0] addr, output reg [23:0] data);\n")
            f.write("    always @* begin\n        case (addr)\n")
            for a, (d, l) in enumerate(t):
                f.write(f"            {abits}'d{a}: data = {{8'd{l}, 16'd{d}}};\n")
            f.write("            default: data = 24'd0;   // end of track\n        endcase\n    end\nendmodule\n\n")
    return abits, [len(t) for t in tracks], nt

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("src", nargs="?")
    ap.add_argument("--demo", action="store_true")
    ap.add_argument("--seconds", type=float, default=30)
    ap.add_argument("-o", "--out", default="music_rom.v")
    a = ap.parse_args()
    if a.demo or not a.src:
        v, name = list(demo()), "original demo loop"
    else:
        v, name = from_audio(a.src, a.seconds), "converted from " + a.src.split("/")[-1]
    abits, lens, nt = emit(v, a.out, name)
    print(f"{a.out}: {nt} ticks ({nt*TICK_S:.1f}s), entries per voice {lens}, addr bits {abits}")